//! `make dev-vault` (Phase 19, V2.29): builds the test vault from
//! `dev/fixtures/entries.json` (D15 + `acme-totp-dev` from D28) through the public API of
//! `ward-core` (validation from Phase 15, body v4 with the configuration from D30 and the
//! generation from D39, the entry writer from D27/D44) and reopens it with the test
//! password to verify it. A freshly created vault is always at generation 1, and the
//! entries are born without the dates of D65 d (only the daemon stamps them, by its own
//! clock; the screen does not show the footer). The test PIN of the fixture only enters
//! the vault as an Argon2id hash (D30); never in clear.
//!
//! Usage (from the root; `make` passes the arguments):
//!
//! ```text
//! dev-vault [--output .dev/<name>.ward]                 creates (or recreates) the vault
//! dev-vault [--output …] --verify [--password-stdin]    only opens and verifies
//! dev-vault [--output …] --cross < patterns.tsv         cross test (V2.57)
//! ```
//!
//! `--cross` (Phase 19e, D54, V2.57): reads from stdin, one per line, `entry<TAB>kind<TAB>
//! pattern in hex` (generated by `dev/tests/dev-vault.sh` from `dev/variations.py`),
//! opens the test vault and runs each pattern, alone, through the mask of the entry it
//! came from (with that entry's delivery, built with fake resources). The whole-value
//! kind: the output must be `••••`. The url kind (the `DATABASE_URL`, which
//! depends on the host and port of whoever runs it): it must have `••••` and no piece of
//! 6+ bytes of a secret of the entry. It only prints counts, entry names and the pattern
//! number; never the pattern.
//!
//! Rules (S15, R19):
//! - The output must stay inside `<root>/.dev/`. The check is done first on the text of
//!   the path only (nothing outside the repository is even looked up on disk) and then on
//!   disk: no component may be a symbolic link, and the target, if it exists, must be a
//!   regular file.
//! - Inputs read only from inside the repository: the private key in
//!   `.dev/services/keys/` (generated by `make dev-services`) and the attachments in
//!   `dev/fixtures/attachments/`, without symbolic links.
//! - No secret goes to argv, stdout, stderr or an error message: only entry names, field
//!   names and levels, and from the configuration only the parameters of the PIN hash (not
//!   the hash), the lock time and the backup state.
//!
//! Example of `ward-core` (not an installed binary): it only exists for development.

