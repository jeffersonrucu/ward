/// Root of the repository (two levels above this crate), already canonical.
fn root() -> Result<PathBuf, Error> {
    let r = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .map_err(|_| Error::Vault("raiz do repositório não encontrada".into()))?;
    if !r.join("Cargo.toml").is_file() || !r.join(FIXTURES).is_file() {
        return Err(Error::Vault("raiz do repositório sem as fixtures".into()));
    }
    Ok(r)
}

/// Absolute path from the text only: relative is relative to the root; `..` is refused.
fn lexical_absolute(root: &Path, requested: &Path) -> Option<PathBuf> {
    if requested
        .components()
        .any(|c| matches!(c, Component::ParentDir))
    {
        return None;
    }
    let p = if requested.is_absolute() {
        requested.to_path_buf()
    } else {
        root.join(requested)
    };
    // `components()` already drops the `.` in the middle; rebuild the path without them.
    Some(p.components().collect())
}

/// Verifies the output path (V2.29: refuses outside `.dev/`).
fn validate_output(root: &Path, requested: &OsStr) -> Result<PathBuf, Error> {
    let requested = Path::new(requested);
    let abs = lexical_absolute(root, requested).ok_or(Error::Output("não pode ter '..'"))?;
    let dev = root.join(DEV_DIR);
    // 1) Text only: nothing outside the repository is looked up on disk.
    let rel = abs
        .strip_prefix(&dev)
        .map_err(|_| Error::Output("tem de ficar dentro de .dev/ do repositório"))?;
    let name = rel
        .file_name()
        .and_then(OsStr::to_str)
        .ok_or(Error::Output("sem nome de arquivo"))?;
    if rel.as_os_str().is_empty() || name.starts_with('.') || !name.ends_with(".ward") {
        return Err(Error::Output(
            "o nome tem de terminar em .ward e não começar com '.'",
        ));
    }
    if name.len() <= ".ward".len() {
        return Err(Error::Output("nome vazio"));
    }
    // 2) Disk: `.dev` is a real directory (created 0700 if missing), a direct child of the
    //    root, and no component up to the target is a symbolic link.
    match fs::symlink_metadata(&dev) {
        Ok(m) if m.file_type().is_dir() => {}
        Ok(_) => return Err(Error::Output(".dev não é um diretório (link simbólico?)")),
        Err(e) if e.kind() == io::ErrorKind::NotFound => {
            DirBuilder::new()
                .mode(0o700)
                .create(&dev)
                .map_err(|_| Error::Output("não deu para criar .dev/"))?;
        }
        Err(_) => return Err(Error::Output("não deu para ler .dev/")),
    }
    if dev.canonicalize().ok().as_deref() != Some(dev.as_path()) {
        return Err(Error::Output(".dev não fica na raiz do repositório"));
    }
    let mut current = dev.clone();
    let parts: Vec<Component<'_>> = rel.components().collect();
    let (last, middle) = parts
        .split_last()
        .ok_or(Error::Output("sem nome de arquivo"))?;
    for c in middle {
        current.push(c);
        match fs::symlink_metadata(&current) {
            Ok(m) if m.file_type().is_dir() => {}
            Ok(_) => return Err(Error::Output("um diretório do caminho é link simbólico")),
            Err(_) => return Err(Error::Output("diretório do caminho não existe")),
        }
    }
    current.push(last);
    match fs::symlink_metadata(&current) {
        Ok(m) if m.file_type().is_file() => {}
        Ok(_) => return Err(Error::Output("o destino existe e não é arquivo comum")),
        Err(e) if e.kind() == io::ErrorKind::NotFound => {}
        Err(_) => return Err(Error::Output("não deu para ler o destino")),
    }
    Ok(current)
}

/// Where a file named in the fixtures comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Source {
    Key,
    Attachment,
}

/// Reads a file named in the fixtures: relative to the root, inside the base of the
/// source, without `..` or a symbolic link in any component, a regular file, up to the
/// limit.
fn read_from_repo(root: &Path, source: Source, path: &str) -> Result<Secret, Error> {
    let (base, max, missing) = match source {
        Source::Key => (
            KEYS_BASE,
            MAX_KEY,
            "não existe; rode make dev-services antes",
        ),
        Source::Attachment => (ATTACHMENTS_BASE, MAX_ATTACHMENT, "não existe"),
    };
    let error = |reason| Error::File {
        which: path.to_owned(),
        reason,
    };
    let requested = Path::new(path);
    if requested.is_absolute() {
        return Err(error("tem de ser relativo à raiz do repositório"));
    }
    let abs = lexical_absolute(root, requested).ok_or_else(|| error("não pode ter '..'"))?;
    let rel = abs
        .strip_prefix(root.join(base))
        .map_err(|_| error("fora da pasta permitida"))?;
    if rel.as_os_str().is_empty() {
        return Err(error("sem nome de arquivo"));
    }
    let mut current = root.to_path_buf();
    let parts: Vec<Component<'_>> = abs
        .strip_prefix(root)
        .map_err(|_| error("fora do repositório"))?
        .components()
        .collect();
    let (last, middle) = parts.split_last().ok_or_else(|| error("sem nome"))?;
    for c in middle {
        current.push(c);
        match fs::symlink_metadata(&current) {
            Ok(m) if m.file_type().is_dir() => {}
            Ok(_) => return Err(error("um diretório do caminho é link simbólico")),
            Err(_) => return Err(error(missing)),
        }
    }
    current.push(last);
    let before = match fs::symlink_metadata(&current) {
        Ok(m) if m.file_type().is_file() => m,
        Ok(_) => return Err(error("não é arquivo comum (link simbólico?)")),
        Err(_) => return Err(error(missing)),
    };
    if before.len() > max {
        return Err(error("grande demais"));
    }
    let f = File::open(&current).map_err(|_| error("não deu para abrir"))?;
    let after = f.metadata().map_err(|_| error("não deu para ler"))?;
    // What was opened is the same file that was verified (a swap in the middle is
    // refused).
    if (after.dev(), after.ino()) != (before.dev(), before.ino()) {
        return Err(error("o arquivo mudou durante a leitura"));
    }
    // Exact capacity before reading: the secret does not go through a reallocation.
    let size = usize::try_from(after.len()).map_err(|_| error("grande demais"))?;
    let mut bytes = Vec::with_capacity(size);
    f.take(max)
        .read_to_end(&mut bytes)
        .map_err(|_| error("não deu para ler"))?;
    let secret = Secret::from_bytes(bytes);
    if secret.len() != size {
        return Err(error("o arquivo mudou durante a leitura"));
    }
    Ok(secret)
}

fn read_fixtures(root: &Path) -> Result<Zeroizing<Vec<u8>>, Error> {
    let path = root.join(FIXTURES);
    let error = |reason| Error::File {
        which: FIXTURES.to_owned(),
        reason,
    };
    let meta = fs::symlink_metadata(&path).map_err(|_| error("não existe"))?;
    if !meta.file_type().is_file() {
        return Err(error("não é arquivo comum"));
    }
    if meta.len() > MAX_FIXTURES {
        return Err(error("grande demais"));
    }
    let size = usize::try_from(meta.len()).map_err(|_| error("grande demais"))?;
    let mut buf = Zeroizing::new(Vec::with_capacity(size + 1));
    File::open(&path)
        .and_then(|f| f.take(MAX_FIXTURES + 1).read_to_end(&mut buf))
        .map_err(|_| error("não deu para ler"))?;
    if buf.len() as u64 > MAX_FIXTURES {
        return Err(error("grande demais"));
    }
    Ok(buf)
}

// --- JSON (only what the fixtures use; strict) ------------------------------------------
//
// No new dependency (S14): objects, lists, strings with escapes, integers, booleans and
// null. A repeated key, a number with a fraction/exponent, nesting above 32, a raw control
// character and any byte after the value are refused. The strings are born with their
// final capacity (no reallocation) and are zeroed on exit.

#[derive(Debug)]
enum Value {
    Null,
    Bool(bool),
    Integer(i64),
    Text(Zeroizing<String>),
    List(Vec<Value>),
    Object(Vec<(String, Value)>),
}

const MAX_JSON_DEPTH: usize = 32;

struct Reader<'a> {
    b: &'a [u8],
    i: usize,
}

fn json(b: &[u8]) -> Result<Value, Error> {
    let mut l = Reader { b, i: 0 };
    let v = l.value(0)?;
    l.skip_space();
    if l.i != b.len() {
        return Err(l.error("sobra depois do valor"));
    }
    Ok(v)
}

impl Reader<'_> {
    fn error(&self, reason: &'static str) -> Error {
        Error::Json {
            pos: self.i,
            reason,
        }
    }

    fn skip_space(&mut self) {
        while let Some(b' ' | b'\t' | b'\n' | b'\r') = self.b.get(self.i) {
            self.i += 1;
        }
    }

    fn literal(&mut self, s: &[u8]) -> bool {
        if self.b[self.i..].starts_with(s) {
            self.i += s.len();
            true
        } else {
            false
        }
    }

    fn value(&mut self, depth: usize) -> Result<Value, Error> {
        if depth > MAX_JSON_DEPTH {
            return Err(self.error("aninhamento demais"));
        }
        self.skip_space();
        match self.b.get(self.i) {
            Some(b'{') => self.object(depth),
            Some(b'[') => self.list(depth),
            Some(b'"') => Ok(Value::Text(self.text()?)),
            Some(b'-' | b'0'..=b'9') => self.integer(),
            Some(b't') if self.literal(b"true") => Ok(Value::Bool(true)),
            Some(b'f') if self.literal(b"false") => Ok(Value::Bool(false)),
            Some(b'n') if self.literal(b"null") => Ok(Value::Null),
            Some(_) => Err(self.error("valor inválido")),
            None => Err(self.error("fim inesperado")),
        }
    }

    fn object(&mut self, depth: usize) -> Result<Value, Error> {
        self.i += 1;
        let mut fields: Vec<(String, Value)> = Vec::new();
        self.skip_space();
        if self.b.get(self.i) == Some(&b'}') {
            self.i += 1;
            return Ok(Value::Object(fields));
        }
        loop {
            self.skip_space();
            if self.b.get(self.i) != Some(&b'"') {
                return Err(self.error("esperava o nome do campo"));
            }
            let key = String::clone(&*self.text()?);
            if fields.iter().any(|(k, _)| *k == key) {
                return Err(self.error("campo repetido"));
            }
            self.skip_space();
            if self.b.get(self.i) != Some(&b':') {
                return Err(self.error("esperava ':'"));
            }
            self.i += 1;
            let v = self.value(depth + 1)?;
            fields.push((key, v));
            self.skip_space();
            match self.b.get(self.i) {
                Some(b',') => self.i += 1,
                Some(b'}') => {
                    self.i += 1;
                    return Ok(Value::Object(fields));
                }
                _ => return Err(self.error("esperava ',' ou '}'")),
            }
        }
    }

    fn list(&mut self, depth: usize) -> Result<Value, Error> {
        self.i += 1;
        let mut items = Vec::new();
        self.skip_space();
        if self.b.get(self.i) == Some(&b']') {
            self.i += 1;
            return Ok(Value::List(items));
        }
        loop {
            items.push(self.value(depth + 1)?);
            self.skip_space();
            match self.b.get(self.i) {
                Some(b',') => self.i += 1,
                Some(b']') => {
                    self.i += 1;
                    return Ok(Value::List(items));
                }
                _ => return Err(self.error("esperava ',' ou ']'")),
            }
        }
    }

    fn integer(&mut self) -> Result<Value, Error> {
        let start = self.i;
        if self.b[self.i] == b'-' {
            self.i += 1;
        }
        let dig = self.i;
        while let Some(b'0'..=b'9') = self.b.get(self.i) {
            self.i += 1;
        }
        if self.i == dig || (self.b[dig] == b'0' && self.i - dig > 1) {
            return Err(self.error("número inválido"));
        }
        if let Some(b'.' | b'e' | b'E') = self.b.get(self.i) {
            return Err(self.error("só números inteiros"));
        }
        std::str::from_utf8(&self.b[start..self.i])
            .ok()
            .and_then(|s| s.parse::<i64>().ok())
            .map(Value::Integer)
            .ok_or_else(|| self.error("número fora do limite"))
    }

    fn hex4(&mut self) -> Result<u32, Error> {
        let h = self
            .b
            .get(self.i..self.i + 4)
            .ok_or_else(|| self.error("escape \\u incompleto"))?;
        let s = std::str::from_utf8(h).map_err(|_| self.error("escape \\u inválido"))?;
        if !s.bytes().all(|c| c.is_ascii_hexdigit()) {
            return Err(self.error("escape \\u inválido"));
        }
        self.i += 4;
        u32::from_str_radix(s, 16).map_err(|_| self.error("escape \\u inválido"))
    }

    fn text(&mut self) -> Result<Zeroizing<String>, Error> {
        self.i += 1; // quotes
        // 1st pass: finds the end and the maximum size, without copying.
        let mut j = self.i;
        loop {
            match self.b.get(j) {
                None => {
                    return Err(Error::Json {
                        pos: j,
                        reason: "texto sem fim",
                    });
                }
                Some(b'"') => break,
                Some(b'\\') => j += 2,
                Some(_) => j += 1,
            }
        }
        let mut s = Zeroizing::new(String::with_capacity(j - self.i));
        // 2nd pass: decodes.
        let mut raw = self.i;
        while self.i < self.b.len() {
            let c = self.b[self.i];
            match c {
                b'"' => {
                    let chunk = std::str::from_utf8(&self.b[raw..self.i])
                        .map_err(|_| self.error("texto não é UTF-8"))?;
                    s.push_str(chunk);
                    self.i += 1;
                    return Ok(s);
                }
                0x00..=0x1f => return Err(self.error("caractere de controle no texto")),
                b'\\' => {
                    let chunk = std::str::from_utf8(&self.b[raw..self.i])
                        .map_err(|_| self.error("texto não é UTF-8"))?;
                    s.push_str(chunk);
                    self.i += 1;
                    let e = *self
                        .b
                        .get(self.i)
                        .ok_or_else(|| self.error("escape sem fim"))?;
                    self.i += 1;
                    let ch = match e {
                        b'"' => '"',
                        b'\\' => '\\',
                        b'/' => '/',
                        b'b' => '\u{8}',
                        b'f' => '\u{c}',
                        b'n' => '\n',
                        b'r' => '\r',
                        b't' => '\t',
                        b'u' => {
                            let high = self.hex4()?;
                            let cp = if (0xd800..0xdc00).contains(&high) {
                                if !self.literal(b"\\u") {
                                    return Err(self.error("par substituto incompleto"));
                                }
                                let low = self.hex4()?;
                                if !(0xdc00..0xe000).contains(&low) {
                                    return Err(self.error("par substituto inválido"));
                                }
                                0x10000 + ((high - 0xd800) << 10) + (low - 0xdc00)
                            } else {
                                high
                            };
                            char::from_u32(cp).ok_or_else(|| self.error("escape \\u inválido"))?
                        }
                        _ => return Err(self.error("escape inválido")),
                    };
                    s.push(ch);
                    raw = self.i;
                }
                _ => self.i += 1,
            }
        }
        Err(self.error("texto sem fim"))
    }
}

// --- Fixtures → drafts → entries --------------------------------------------------------

/// JSON object consumed field by field; at the end, a field left over is an error.
struct Obj {
    at: String,
    fields: Vec<(String, Value)>,
}

impl Obj {
    fn from_value(at: impl Into<String>, v: Value) -> Result<Self, Error> {
        let at = at.into();
        match v {
            Value::Object(fields) => Ok(Obj { at, fields }),
            _ => Err(fixture(at, "esperava um objeto")),
        }
    }

    fn take(&mut self, key: &str) -> Option<Value> {
        let i = self.fields.iter().position(|(k, _)| k == key)?;
        Some(self.fields.remove(i).1)
    }

    fn text(&mut self, key: &str) -> Result<Option<Zeroizing<String>>, Error> {
        match self.take(key) {
            None | Some(Value::Null) => Ok(None),
            Some(Value::Text(t)) => Ok(Some(t)),
            Some(_) => Err(fixture(format!("{}.{key}", self.at), "esperava texto")),
        }
    }

    /// Plain text (not a secret); missing = empty.
    fn plain(&mut self, key: &str) -> Result<String, Error> {
        Ok(self
            .text(key)?
            .map(|t| String::clone(&t))
            .unwrap_or_default())
    }

    fn required(&mut self, key: &str) -> Result<String, Error> {
        let v = self.plain(key)?;
        if v.is_empty() {
            return Err(fixture(format!("{}.{key}", self.at), "obrigatório"));
        }
        Ok(v)
    }

    /// Port: number or text; missing = empty (the validation uses the default one).
    fn port(&mut self, key: &str) -> Result<String, Error> {
        match self.take(key) {
            None | Some(Value::Null) => Ok(String::new()),
            Some(Value::Integer(n)) => Ok(n.to_string()),
            Some(Value::Text(t)) => Ok(String::clone(&t)),
            Some(_) => Err(fixture(
                format!("{}.{key}", self.at),
                "esperava número ou texto",
            )),
        }
    }

    /// Secret as text; the `String` is moved into the core's secret type, without a copy.
    fn secret(&mut self, key: &str) -> Result<Option<Secret>, Error> {
        Ok(self
            .text(key)?
            .map(|mut t| Secret::from_text(std::mem::take(&mut *t))))
    }

    fn finish(self) -> Result<(), Error> {
        match self.fields.first() {
            None => Ok(()),
            Some((k, _)) => Err(fixture(format!("{}.{k}", self.at), "campo desconhecido")),
        }
    }
}

type ReadFn<'a> = dyn FnMut(Source, &str) -> Result<Secret, Error> + 'a;

/// What the fixtures give: master password, PIN (in memory that is zeroed on exit) and
/// entries.
type Built = (MasterPassword, Zeroizing<String>, Vec<Entry>);

/// Builds the master password, the PIN and the validated entries (with the level of the
/// fixture) from the JSON. `read` reads the files named there (private key,
/// attachments).
fn build(bytes: &[u8], read: &mut ReadFn<'_>) -> Result<Built, Error> {
    let mut top = Obj::from_value("(raiz)", json(bytes)?)?;
    let _ = top.text("_sobre")?;
    match top.take("versao") {
        Some(Value::Integer(1)) => {}
        _ => return Err(fixture("versao", "tem de ser 1")),
    }
    let password = top
        .text("senha_mestra")?
        .filter(|t| !t.is_empty())
        .ok_or_else(|| fixture("senha_mestra", "obrigatória"))?;
    let pin = top
        .text("pin")?
        .ok_or_else(|| fixture("pin", "obrigatório"))?;
    if pin.len() != 6 || !pin.bytes().all(|b| b.is_ascii_digit()) {
        return Err(fixture("pin", "tem de ter 6 dígitos"));
    }
    let list = match top.take("entradas") {
        Some(Value::List(l)) => l,
        _ => return Err(fixture("entradas", "esperava uma lista")),
    };
    top.finish()?;

    let mut entries = Vec::with_capacity(list.len());
    for (i, v) in list.into_iter().enumerate() {
        entries.push(entry(i, v, read)?);
    }
    let password = MasterPassword::new(String::clone(&password));
    Ok((password, pin, entries))
}

fn entry(i: usize, v: Value, read: &mut ReadFn<'_>) -> Result<Entry, Error> {
    let mut e = Obj::from_value(format!("entradas[{i}]"), v)?;
    let name = e.required("nome")?;
    e.at = name.clone();
    let kind_text = e.required("tipo")?;
    let kind = EntryType::from_name(&kind_text)
        .ok_or_else(|| fixture(name.as_str(), "tipo desconhecido"))?;
    let level = AccessLevel::from_name(&e.required("nivel")?)
        .ok_or_else(|| fixture(name.as_str(), "nível desconhecido"))?;
    let group = e.plain("grupo")?;
    let environment = e.plain("ambiente")?;
    let project = e.plain("projeto")?;
    let tags = match e.take("tags") {
        None | Some(Value::Null) => Vec::new(),
        Some(Value::List(l)) => l
            .into_iter()
            .map(|t| match t {
                Value::Text(t) => Ok(String::clone(&t)),
                _ => Err(fixture(format!("{name}.tags"), "esperava texto")),
            })
            .collect::<Result<_, _>>()?,
        Some(_) => return Err(fixture(format!("{name}.tags"), "esperava lista")),
    };
    let fields = Obj::from_value(
        format!("{name}.campos"),
        e.take("campos").unwrap_or(Value::Object(Vec::new())),
    )?;
    let secrets = Obj::from_value(
        format!("{name}.segredos"),
        e.take("segredos").unwrap_or(Value::Object(Vec::new())),
    )?;
    let data = data(kind, fields, secrets, read)?;

    let mut extras = Vec::new();
    match e.take("extras") {
        None | Some(Value::Null) => {}
        Some(Value::List(l)) => {
            for (j, x) in l.into_iter().enumerate() {
                let mut x = Obj::from_value(format!("{name}.extras[{j}]"), x)?;
                let extra_name = x.required("nome")?;
                let value = x
                    .secret("valor")?
                    .ok_or_else(|| fixture(format!("{name}.extras[{j}].valor"), "obrigatório"))?;
                let secret = match x.take("segredo") {
                    Some(Value::Bool(b)) => b,
                    _ => {
                        return Err(fixture(
                            format!("{name}.extras[{j}].segredo"),
                            "esperava true ou false",
                        ));
                    }
                };
                x.finish()?;
                extras.push(ExtraDraft {
                    name: extra_name,
                    value,
                    secret,
                });
            }
        }
        Some(_) => return Err(fixture(format!("{name}.extras"), "esperava lista")),
    }

    let mut attachments = Vec::new();
    match e.take("anexos") {
        None | Some(Value::Null) => {}
        Some(Value::List(l)) => {
            for (j, a) in l.into_iter().enumerate() {
                let mut a = Obj::from_value(format!("{name}.anexos[{j}]"), a)?;
                let attachment_name = a.required("nome")?;
                let file = a.required("arquivo")?;
                a.finish()?;
                attachments.push(AttachmentDraft {
                    name: attachment_name,
                    content: read(Source::Attachment, &file)?,
                });
            }
        }
        Some(_) => return Err(fixture(format!("{name}.anexos"), "esperava lista")),
    }
    e.finish()?;

    let r = Draft {
        name: name.clone(),
        group,
        environment,
        project,
        tags,
        data,
        extras,
        attachments,
    };
    // The validation of Phase 15 is the same one of the app; the error only has fixed
    // texts.
    let mut validated = r.validate().map_err(|e| fixture(name, e.to_string()))?;
    // Only the daemon changes a level after the PIN (S9); here it is the assembly of the
    // test vault, which is born with the levels of the contract table.
    validated.set_level(level);
    Ok(validated)
}

fn data(
    kind: EntryType,
    mut c: Obj,
    mut s: Obj,
    read: &mut ReadFn<'_>,
) -> Result<DataDraft, Error> {
    let mut key = |s: &mut Obj| -> Result<Option<Secret>, Error> {
        match s.text("chave_privada_arquivo")? {
            None => Ok(None),
            Some(path) => read(Source::Key, &path).map(Some),
        }
    };
    let d = match kind {
        EntryType::Login => DataDraft::Login {
            url: c.plain("url")?,
            username: c.plain("usuario")?,
            password: s.secret("senha")?,
            totp_seed: s.secret("totp_semente")?,
        },
        EntryType::Database => DataDraft::Database {
            engine: c.plain("motor")?,
            host: c.plain("host")?,
            port: c.port("porta")?,
            db_name: c.plain("base")?,
            username: c.plain("usuario")?,
            password: s.secret("senha")?,
            tunnel: c.plain("tunel")?,
        },
        EntryType::Server => DataDraft::Server {
            host: c.plain("host")?,
            port: c.port("porta")?,
            username: c.plain("usuario")?,
            password: s.secret("senha")?,
            private_key: key(&mut s)?,
            passphrase: s.secret("passphrase")?,
            jump: c.plain("salto")?,
        },
        EntryType::Api => DataDraft::Api {
            url: c.plain("url")?,
            token: s.secret("token")?,
            variable: c.plain("variavel")?,
        },
        EntryType::Aws => DataDraft::Aws {
            access_key_id: c.plain("access_key_id")?,
            secret_access_key: s.secret("secret_access_key")?,
            region: c.plain("regiao")?,
            role_arn: c.plain("role_arn")?,
            session_token: s.secret("session_token")?,
        },
        EntryType::Smtp => DataDraft::Smtp {
            host: c.plain("host")?,
            port: c.port("porta")?,
            username: c.plain("usuario")?,
            password: s.secret("senha")?,
            security: c.plain("seguranca")?,
        },
        EntryType::FtpSftp => DataDraft::FtpSftp {
            protocol: c.plain("protocolo")?,
            host: c.plain("host")?,
            port: c.port("porta")?,
            username: c.plain("usuario")?,
            password: s.secret("senha")?,
            private_key: key(&mut s)?,
            passphrase: s.secret("passphrase")?,
        },
        EntryType::SecureNote => DataDraft::SecureNote {
            text: s.secret("texto")?,
        },
        EntryType::Generic => DataDraft::Generic,
    };
    c.finish()?;
    s.finish()?;
    Ok(d)
}

