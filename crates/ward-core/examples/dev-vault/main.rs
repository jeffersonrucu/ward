// --- Errors (only fixed text, entry/field names and repository paths) ----------------

#[derive(Debug)]
enum Error {
    Usage(&'static str),
    /// Output path refused.
    Output(&'static str),
    /// Input file (key, attachment, fixtures) refused or unreadable.
    File {
        which: String,
        reason: &'static str,
    },
    Json {
        pos: usize,
        reason: &'static str,
    },
    /// Fixture with the wrong shape: where (entry.field) and why, without the value.
    Fixture {
        at: String,
        reason: String,
    },
    Vault(String),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::Usage(m) => write!(
                f,
                "{m}\nuso: dev-vault [--output .dev/<nome>.ward] [--verify [--password-stdin] | --cross]"
            ),
            Error::Output(m) => write!(f, "caminho de saída recusado: {m}"),
            Error::File { which, reason } => write!(f, "{which}: {reason}"),
            Error::Json { pos, reason } => write!(f, "{FIXTURES}: byte {pos}: {reason}"),
            Error::Fixture { at, reason } => write!(f, "{FIXTURES}: {at}: {reason}"),
            Error::Vault(m) => f.write_str(m),
        }
    }
}

fn fixture(at: impl Into<String>, reason: impl Into<String>) -> Error {
    Error::Fixture {
        at: at.into(),
        reason: reason.into(),
    }
}

// --- Command line ---------------------------------------------------------------------

#[derive(Debug, Default)]
struct Options {
    output: Option<OsString>,
    verify: bool,
    password_stdin: bool,
    cross: bool,
}

fn read_options(args: impl Iterator<Item = OsString>) -> Result<Options, Error> {
    let mut o = Options::default();
    let mut args = args;
    while let Some(a) = args.next() {
        match a.to_str() {
            Some("--output") => {
                let v = args.next().ok_or(Error::Usage("--output sem caminho"))?;
                if o.output.replace(v).is_some() {
                    return Err(Error::Usage("--output repetido"));
                }
            }
            Some("--verify") => o.verify = true,
            Some("--password-stdin") => o.password_stdin = true,
            Some("--cross") => o.cross = true,
            _ => return Err(Error::Usage("argumento desconhecido")),
        }
    }
    if o.cross && (o.verify || o.password_stdin) {
        return Err(Error::Usage(
            "--cross não vale com --verify nem --password-stdin",
        ));
    }
    if o.password_stdin && !o.verify {
        return Err(Error::Usage("--password-stdin só vale com --verify"));
    }
    Ok(o)
}

fn run(args: impl Iterator<Item = OsString>) -> Result<(), Error> {
    let options = read_options(args)?;
    let root = root()?;
    let requested = options
        .output
        .clone()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| OsString::from(DEFAULT_OUTPUT));
    let output = validate_output(&root, &requested)?;
    let shown = output.strip_prefix(&root).unwrap_or(&output).display();

    let fixtures = read_fixtures(&root)?;
    let mut read = |source: Source, path: &str| read_from_repo(&root, source, path);
    let (password, pin, expected) = build(&fixtures, &mut read)?;
    drop(fixtures);

    if options.cross {
        verify(&output, &password, &pin, &expected)?;
        return cross(&output, &password);
    }

    if options.verify {
        let password = if options.password_stdin {
            password_from_stdin()?
        } else {
            password
        };
        let (n, generation) = verify(&output, &password, &pin, &expected)?;
        println!("dev-vault: {shown} abre com a senha e tem as {n} entradas das fixtures");
        print_config(generation);
        print_list(&expected);
        return Ok(());
    }

    // D30: the vault is born with the configuration (hash of the test PIN, default lock,
    // backup off). The PIN only exists here, in memory that is zeroed on exit.
    let hash = PinHash::create(pin.as_bytes())
        .map_err(|e| Error::Vault(format!("não deu para criar o hash do PIN: {e}")))?;
    let mut vault = OpenVault::new(&password, VaultConfig::new(hash))
        .map_err(|e| Error::Vault(format!("não deu para criar o cofre: {e}")))?;
    write_entries(&output, &mut vault, &expected)
        .map_err(|e| Error::Vault(format!("não deu para gravar {shown}: {e}")))?;
    drop(vault);
    let (n, generation) = verify(&output, &password, &pin, &expected)?;
    // D39: a freshly created vault is at generation 1.
    if generation != NEW_GENERATION {
        return Err(Error::Vault(
            "o cofre gravado não está na geração de um cofre novo".into(),
        ));
    }
    println!("dev-vault: gravado {shown} (0600) com {n} entradas; reaberto e conferido");
    print_config(generation);
    print_list(&expected);
    Ok(())
}

/// What the verification guaranteed about the configuration (none of it is secret; the
/// hash does not come out).
fn print_config(generation: u64) {
    println!(
        "dev-vault: configuração: geração {generation}, hash do PIN Argon2id (m={} KiB, t={}, p={}), trava em {} min, backup externo desligado",
        KDF_PIN.memory_kib, KDF_PIN.passes, KDF_PIN.parallelism, DEFAULT_LOCK_MINUTES
    );
}

/// Name, kind and level of each entry (none of it is secret).
fn print_list(entries: &[Entry]) {
    let mut names: Vec<&Entry> = entries.iter().collect();
    names.sort_by(|a, b| a.name().cmp(b.name()));
    for e in names {
        println!("  {}\t{}\t{}", e.name(), e.kind().name(), e.level().name());
    }
}

/// Password from stdin (only for the wrong password test), without echo and without
/// argv.
fn password_from_stdin() -> Result<MasterPassword, Error> {
    let mut buf = Zeroizing::new(Vec::with_capacity(256));
    io::stdin()
        .take(256)
        .read_to_end(&mut buf)
        .map_err(|_| Error::Usage("não deu para ler a senha do stdin"))?;
    while buf.last().is_some_and(|b| *b == b'\n' || *b == b'\r') {
        buf.pop();
    }
    let mut bytes = Zeroizing::new(Vec::with_capacity(buf.len()));
    bytes.extend_from_slice(&buf);
    Ok(MasterPassword::from_bytes(bytes))
}

/// Reopens the file and verifies that the entries come back equal to the fixtures (same
/// bytes of the canonical body, so same fields, secrets and levels) and that the
/// configuration is the one of the test vault (D30): the fixture PIN matches the hash, a
/// wrong PIN does not, the hash uses the default parameters, the lock is the default one
/// and the backup is off.
fn verify(
    output: &Path,
    password: &MasterPassword,
    pin: &str,
    expected: &[Entry],
) -> Result<(usize, u64), Error> {
    let meta = fs::symlink_metadata(output)
        .map_err(|_| Error::Vault("o cofre não existe; rode make dev-vault".into()))?;
    if !meta.file_type().is_file() {
        return Err(Error::Vault("o cofre não é um arquivo comum".into()));
    }
    if meta.permissions().mode() & 0o077 != 0 {
        return Err(Error::Vault(
            "o cofre está aberto para grupo ou outros".into(),
        ));
    }
    if meta.len() > MAX_VAULT {
        return Err(Error::Vault("o cofre passa do tamanho máximo".into()));
    }
    let bytes = fs::read(output).map_err(|_| Error::Vault("não deu para ler o cofre".into()))?;
    let (vault, loaded) = open_entries(&bytes, password)
        .map_err(|e| Error::Vault(format!("o cofre não abriu: {e}")))?;
    // D39: the generation read (≥ 1; the reader refuses 0) goes into both sides of the
    // comparison.
    let generation = vault.generation();
    let cfg = vault.config();
    let a = serialize(cfg, generation, &loaded).map_err(|e| Error::Vault(format!("{e}")))?;
    let b = serialize(cfg, generation, expected).map_err(|e| Error::Vault(format!("{e}")))?;
    if *a != *b {
        return Err(Error::Vault(
            "o cofre abre, mas as entradas diferem das fixtures; rode make dev-vault".into(),
        ));
    }
    verify_config(cfg, pin)?;
    Ok((loaded.len(), generation))
}

/// The configuration read is the one of the test vault (without saying anything about
/// the PIN or the hash).
fn verify_config(cfg: &VaultConfig, pin: &str) -> Result<(), Error> {
    let wrong = Zeroizing::new(neighbor_pin(pin));
    if !cfg.verify_pin(pin.as_bytes()) || cfg.verify_pin(wrong.as_bytes()) {
        return Err(Error::Vault(
            "o hash do PIN do cofre não é o do PIN das fixtures; rode make dev-vault".into(),
        ));
    }
    if cfg.pin_hash().params() != KDF_PIN
        || cfg.lock_minutes() != DEFAULT_LOCK_MINUTES
        || cfg.backup().enabled()
        || cfg.backup().uuid().is_some()
    {
        return Err(Error::Vault(
            "a configuração do cofre não é a padrão; rode make dev-vault".into(),
        ));
    }
    Ok(())
}

// --- Cross test oracle → mask (V2.57) ---------------------------------------------------

/// Fake resources to build the delivery of each entry (the TOTP code and the path do not
/// go into the mask; the tunnel port is any one).
struct FakeResources;

impl Resources for FakeResources {
    fn totp_code(&mut self, _: &Secret) -> Result<Zeroizing<String>, ResourceError> {
        Ok(Zeroizing::new(String::from("000000")))
    }
    fn file(&mut self, name: &str, _: &Secret) -> Result<String, ResourceError> {
        Ok(format!("/run/user/0/ward-teste/{name}"))
    }
    fn tunnel(&mut self, _: &str, _: &str, _: u16) -> Result<u16, ResourceError> {
        Ok(40123)
    }
}

/// Largest pattern accepted in a stdin line (the largest attachment of D29 in hex, with
/// room to spare).
const MAX_CROSS_LINE: usize = 4 * MAX_ATTACHMENTS_TOTAL + 1024;

fn hex_to_bytes(h: &[u8]) -> Option<Zeroizing<Vec<u8>>> {
    if !h.len().is_multiple_of(2) {
        return None;
    }
    let digit = |c: u8| (c as char).to_digit(16).map(|d| d as u8);
    let mut v = Zeroizing::new(Vec::with_capacity(h.len() / 2));
    for pair in h.chunks(2) {
        v.push((digit(pair[0])? << 4) | digit(pair[1])?);
    }
    Some(v)
}

/// Some piece of 6 bytes or more of some secret of the entry is left in the output.
fn secret_left(output: &[u8], e: &Entry) -> bool {
    e.secrets().iter().any(|s| {
        let v = s.value.expose();
        v.len() >= 6 && v.windows(6).any(|j| output.windows(6).any(|w| w == j))
    })
}

/// V2.57: each pattern of the oracle, alone, comes out `••••` through the mask of its
/// entry.
fn cross(output: &Path, password: &MasterPassword) -> Result<(), Error> {
    let bytes = fs::read(output).map_err(|_| Error::Vault("não deu para ler o cofre".into()))?;
    let (_, loaded) = open_entries(&bytes, password)
        .map_err(|e| Error::Vault(format!("o cofre não abriu: {e}")))?;
    let mut tsv = Zeroizing::new(Vec::new());
    io::stdin()
        .take(64 * 1024 * 1024)
        .read_to_end(&mut tsv)
        .map_err(|_| Error::Usage("não deu para ler os padrões do stdin"))?;
    let mut masks: Vec<(String, Mask)> = Vec::new();
    let (mut total, mut failures) = (0usize, 0usize);
    let mut names = std::collections::BTreeSet::new();
    for (i, line) in tsv.split(|b| *b == b'\n').enumerate() {
        if line.is_empty() {
            continue;
        }
        let mut parts = line.splitn(3, |b| *b == b'\t');
        let (Some(name), Some(kind), Some(hex)) = (parts.next(), parts.next(), parts.next()) else {
            return Err(Error::Usage("linha do stdin sem entrada, tipo e padrão"));
        };
        if hex.len() > MAX_CROSS_LINE {
            return Err(Error::Usage("padrão grande demais no stdin"));
        }
        let name = String::from_utf8_lossy(name).into_owned();
        let Some(e) = loaded.iter().find(|e| e.name() == name) else {
            return Err(Error::Vault(format!(
                "cruzado: entrada {name} não está no cofre"
            )));
        };
        let Some(pattern) = hex_to_bytes(hex) else {
            return Err(Error::Usage("padrão do stdin não está em hex"));
        };
        if !masks.iter().any(|(n, _)| *n == name) {
            let g = match delivery::build(e, &mut FakeResources) {
                Ok(g) => Some(g),
                Err(DeliveryError::TypeWithoutDelivery) => None,
                Err(_) => return Err(Error::Vault(format!("cruzado: entrega de {name} falhou"))),
            };
            let m = Mask::from_entry(e, g.as_ref())
                .map_err(|_| Error::Vault(format!("cruzado: máscara de {name} não montou")))?;
            masks.push((name.clone(), m));
        }
        let m = &masks.iter().find(|(n, _)| *n == name).unwrap().1;
        let out = Zeroizing::new(m.mask_all(&pattern));
        let ok = match kind {
            b"inteiro" => out.as_slice() == MARK.as_bytes(),
            b"url" => {
                out.windows(MARK.len()).any(|w| w == MARK.as_bytes()) && !secret_left(&out, e)
            }
            _ => return Err(Error::Usage("tipo de padrão desconhecido no stdin")),
        };
        total += 1;
        names.insert(name.clone());
        if !ok {
            failures += 1;
            eprintln!(
                "dev-vault: cruzado: o padrão da linha {} ({}) de {name} não saiu {MARK}",
                i + 1,
                String::from_utf8_lossy(kind)
            );
        }
    }
    if total == 0 {
        return Err(Error::Usage("nenhum padrão no stdin"));
    }
    if failures > 0 {
        return Err(Error::Vault(format!(
            "cruzado: {failures} de {total} padrões não saíram {MARK}"
        )));
    }
    println!(
        "dev-vault: cruzado: os {total} padrões de {} entradas saem {MARK} pela máscara da entrada",
        names.len()
    );
    Ok(())
}

/// The PIN with the last digit changed (to verify that the hash refuses a wrong PIN).
fn neighbor_pin(pin: &str) -> String {
    let mut s = String::with_capacity(pin.len());
    let n = pin.len();
    for (i, c) in pin.chars().enumerate() {
        if i + 1 == n {
            s.push(if c == '0' { '1' } else { '0' });
        } else {
            s.push(c);
        }
    }
    s
}

